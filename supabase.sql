create table if not exists public.productos (
 id bigint generated by default as identity primary key,
 name text not null check (char_length(name) between 1 and 100),
 category text not null check (category in ('camisetas','zapatos')),
 price numeric(12,2) not null check(price>0),
 old_price numeric(12,2) check(old_price is null or old_price>0),
 sizes text[] not null default '{}',
 description text not null default '',
 image_path text not null,
 created_at timestamptz not null default now()
);
create table if not exists public.admins (user_id uuid primary key references auth.users(id) on delete cascade);
alter table public.productos enable row level security;
alter table public.admins enable row level security;
create or replace function public.is_shop_admin() returns boolean language sql stable security definer set search_path = '' as $$select exists(select 1 from public.admins where user_id=(select auth.uid()))$$;
revoke all on function public.is_shop_admin() from public;
grant execute on function public.is_shop_admin() to authenticated;
drop policy if exists "Public read products" on public.productos;
create policy "Public read products" on public.productos for select to anon,authenticated using(true);
drop policy if exists "Admins insert products" on public.productos;
create policy "Admins insert products" on public.productos for insert to authenticated with check(public.is_shop_admin());
drop policy if exists "Admins update products" on public.productos;
create policy "Admins update products" on public.productos for update to authenticated using(public.is_shop_admin()) with check(public.is_shop_admin());
drop policy if exists "Admins delete products" on public.productos;
create policy "Admins delete products" on public.productos for delete to authenticated using(public.is_shop_admin());
drop policy if exists "Admins read own membership" on public.admins;
create policy "Admins read own membership" on public.admins for select to authenticated using(user_id=(select auth.uid()));
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types) values('productos','productos',true,5242880,array['image/jpeg','image/png']) on conflict(id) do update set public=true,file_size_limit=5242880,allowed_mime_types=array['image/jpeg','image/png'];
drop policy if exists "Public view product photos" on storage.objects;
create policy "Public view product photos" on storage.objects for select to anon,authenticated using(bucket_id='productos');
drop policy if exists "Admins upload product photos" on storage.objects;
create policy "Admins upload product photos" on storage.objects for insert to authenticated with check(bucket_id='productos' and public.is_shop_admin());
drop policy if exists "Admins remove product photos" on storage.objects;
create policy "Admins remove product photos" on storage.objects for delete to authenticated using(bucket_id='productos' and public.is_shop_admin());
